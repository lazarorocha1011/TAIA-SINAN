"""### Critério Adotado para Valores Faltantes

Nesta análise, foi adotado o seguinte critério para classificar um
dado como **faltante**:
- **Strings Vazias (`""`)**: Como o conjunto de dados foi lido com o parâmetro `keep_default_na=False` no pandas, os campos que originalmente estavam em branco no arquivo CSV foram importados como strings vazias em vez do valor padrão `NaN` (Not a Number).
- **Valores Nulos/NaN tradicionais**: Caso existam por qualquer outro motivo de processamento.

**Justificativa:** No contexto de registros de saúde (como o SINAN), campos não preenchidos (em branco) representam a ausência de informação para aquela variável naquele registro específico. Portanto, identificar strings vazias pareceu ser a forma mais precisa de mensurar a completitude de cada atributo sob as configurações atuais de carregamento do DataFrame.
"""

import pandas as pd

