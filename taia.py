"""
---
## 3. Transformação de Valores Impossíveis em Faltante
Identificamos valores que não podem existir logicamente:
- **Idade contínua**: Valores negativos ou acima de 120 anos (encontrados 0 casos; pacientes com idades entre 98 e 114 anos são clinicamente plausíveis e continuam na base).
- **Contatos examinados (`NU_COMU_EX`)**: Códigos especiais como '99', '999' ou negativos convertidos para `np.nan`.
- **Datas e Temporalidade (2014 a 2024)**: Verificação de registros com anos fora do período do estudo (como notificações de 2025) e inconsistências de ordenação cronológica (encerramento ou início de tratamento anterior à data de diagnóstico).
"""

# %%
# ======================================================================================
# 3. ITEM 3: TRANSFORMAÇÃO DE VALORES IMPOSSÍVEIS EM FALTANTE
# ======================================================================================
relatorio_valores_impossiveis = {}

# 1. Checagem de idades impossíveis (< 0 ou > 120)
mask_idade_imp = (df_ativ['IDADE_ANOS'] < 0) | (df_ativ['IDADE_ANOS'] > 120)
qtd_idade_imp = mask_idade_imp.sum()
relatorio_valores_impossiveis['IDADE_ANOS (< 0 ou > 120 anos)'] = qtd_idade_imp
df_ativ.loc[mask_idade_imp, 'IDADE_ANOS'] = np.nan

# 2. Número de contatos examinados impossíveis
df_ativ['NU_COMU_EX_LIMPO'] = pd.to_numeric(df_ativ['NU_COMU_EX'], errors='coerce')
mask_contatos_imp = (df_ativ['NU_COMU_EX_LIMPO'] < 0) | (df_ativ['NU_COMU_EX_LIMPO'] > 200) | (df_ativ['NU_COMU_EX'].isin(['99', '999', '']))
qtd_contatos_imp = mask_contatos_imp.sum()
relatorio_valores_impossiveis['NU_COMU_EX (<0, >200 ou códigos 99/999)'] = qtd_contatos_imp
df_ativ.loc[mask_contatos_imp, 'NU_COMU_EX_LIMPO'] = np.nan

# 3. Checagem de datas fora de 2014 a 2024
anos_validos_estudo = [str(y) for y in range(2014, 2025)]
for col_data in ['DT_DIAG', 'DT_NOTIFIC', 'DT_DIGITA', 'DT_INIC_TR', 'DT_ENCERRA']:
    if col_data in df_ativ.columns:
        mask_fora_ano = (df_ativ[col_data] != '') & (~df_ativ[col_data].str[:4].isin(anos_validos_estudo))
        relatorio_valores_impossiveis[f'{col_data} (ano fora de 2014-2024)'] = mask_fora_ano.sum()

# 4. Inconsistências temporais de sequência
dt_diag_dt = pd.to_datetime(df_ativ['DT_DIAG'], errors='coerce')
dt_enc_dt = pd.to_datetime(df_ativ['DT_ENCERRA'], errors='coerce')
dt_inic_dt = pd.to_datetime(df_ativ['DT_INIC_TR'], errors='coerce')

qtd_enc_ant_diag = (dt_enc_dt < dt_diag_dt).sum()
qtd_inic_ant_diag = (dt_inic_dt < dt_diag_dt).sum()
relatorio_valores_impossiveis['DT_ENCERRA anterior ao diagnóstico (DT_DIAG)'] = qtd_enc_ant_diag
relatorio_valores_impossiveis['DT_INIC_TR anterior ao diagnóstico (DT_DIAG)'] = qtd_inic_ant_diag

print("="*75)
print("ITEM 3: CONTAGEM DE VALORES IMPOSSÍVEIS / INCONSISTENTES IDENTIFICADOS")
