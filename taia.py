# %% [markdown]
"""
---
## 2. Arrumação de Datas e Criação de Colunas Derivadas
*Executado antes do item 3 para viabilizar a checagem de idades impossíveis.*

- **Conversão de Idade (`NU_IDADE_N` para `IDADE_ANOS`)**: No SINAN, a idade vem codificada em 4 dígitos: o 1º dígito identifica a unidade de medida (1=Horas, 2=Dias, 3=Meses, 4=Anos) e os 3 seguintes indicam a quantidade. Casos em horas, dias e meses correspondem a menores de 1 ano (convertidos para 0 anos). Casos com unidade 4 extraem os anos (ex: 4058 -> 58 anos; 4108 -> 108 anos, corrigindo o erro da coluna `IDADE` da base que truncava centenários).
- **Ano do Diagnóstico (`ANO_DIAG`)**: Extraído a partir dos 4 primeiros dígitos de `DT_DIAG` (`YYYY`). É uma informação já existente e fechada no momento da confirmação diagnóstica.
- **Agrupamento Geográfico**: Os códigos de municípios (`ID_MUNICIP` e `ID_MN_RESI`) geram mais de 5.200 categorias altamente esparsas. São agrupados em UF (`SG_UF`) e Região (`REGIAO`), ambas presentes no momento do diagnóstico.
"""

# %%
# ======================================================================================
# 2. ITEM 2: CRIAÇÃO DAS VARIÁVEIS DERIVADAS NO MOMENTO DO DIAGNÓSTICO
# ======================================================================================
def decodificar_idade_sinan(val):
    """
    Decodifica a idade codificada oficial do SINAN (NU_IDADE_N):
    - 4 dígitos: 1=Horas, 2=Dias, 3=Meses, 4=Anos.
    - Menores de 1 ano (1, 2, 3) -> 0.0 anos.
    - Idade em anos (4) -> valor numérico de 1 a 3 dígitos.
    - Preserva centenários (ex: 4108 -> 108 anos).
    """
    s = str(val).split('.')[0].strip()
    if not s or s == '0':
        return np.nan
    if len(s) == 4:
        unidade = s[0]
        try:
            quantidade = int(s[1:])
            if unidade == '4':
                return float(quantidade)
            elif unidade in ('1', '2', '3'):
                return 0.0
        except ValueError:
            return np.nan
    if s.isdigit():
        return float(s)
    return np.nan

# 1. Idade em anos contínua
df_ativ['IDADE_ANOS'] = df_ativ['NU_IDADE_N'].apply(decodificar_idade_sinan)

# 2. Ano de diagnóstico
df_ativ['ANO_DIAG'] = df_ativ['DT_DIAG'].str[:4]

